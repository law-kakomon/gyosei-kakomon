def unit_of(law, art):
    """law は正式名、art は '9' や '37の2' のような文字列。"""
    spec = LAWS.get(ALIASES.get(law, law))
    if not spec:
        return None
    u = spec.get('exact', {}).get(art)
    if u:
        return u
    base = art.split('の')[0]
    if base.isdigit():
        n = int(base)
        for a, b, unit in spec.get('ranges', []):
            if a <= n <= b:
                return unit
    return spec.get('default')


